-- 1. Profiles Table (เชื่อมโยงกับ Supabase Auth)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
    practitioner_name TEXT NOT NULL,
    email TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. Practice Steps (Master Data: 7 ขั้นตอนหลัก)
CREATE TABLE IF NOT EXISTS public.practice_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    step_order INTEGER NOT NULL UNIQUE CHECK (step_order BETWEEN 1 AND 7),
    step_name TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 3. Effort Settings (เกณฑ์ประเมินความเพียรเฉพาะบุคคล ผูกกับ Profile)
CREATE TABLE IF NOT EXISTS public.effort_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL UNIQUE REFERENCES public.profiles(user_id) ON DELETE CASCADE,
    good_days_min INTEGER NOT NULL DEFAULT 20,
    moderate_days_min INTEGER NOT NULL DEFAULT 10,
    excellent_minutes_min INTEGER NOT NULL DEFAULT 61,
    good_minutes_min INTEGER NOT NULL DEFAULT 30,
    moderate_minutes_min INTEGER NOT NULL DEFAULT 20,
    day_weight NUMERIC(3,2) NOT NULL DEFAULT 0.50,
    duration_weight NUMERIC(3,2) NOT NULL DEFAULT 0.50,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 4. Practice Summaries (รอบการปฏิบัติ: User + Step + Round Number)
CREATE TABLE IF NOT EXISTS public.practice_summaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles(user_id) ON DELETE CASCADE,
    practice_step_id BIGINT NOT NULL REFERENCES public.practice_steps(id) ON DELETE RESTRICT,
    round_number INTEGER NOT NULL DEFAULT 1 CHECK (round_number >= 1),
    carried_duration_minutes INTEGER NOT NULL DEFAULT 0 CHECK (carried_duration_minutes >= 0),
    start_date DATE,
    end_date DATE,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused', 'completed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT uq_user_step_round UNIQUE (user_id, practice_step_id, round_number),
    CONSTRAINT chk_dates CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

-- 5. Practice Sessions (Transactions: บันทึกการปฏิบัติแต่ละครั้ง ผูกกับ Summary)
CREATE TABLE IF NOT EXISTS public.practice_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles(user_id) ON DELETE CASCADE,
    practice_summary_id BIGINT NOT NULL REFERENCES public.practice_summaries(id) ON DELETE CASCADE,
    practice_date DATE NOT NULL DEFAULT CURRENT_DATE,
    started_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    duration_seconds INTEGER NOT NULL DEFAULT 0 CHECK (duration_seconds >= 0),
    result_note TEXT,
    source TEXT NOT NULL DEFAULT 'timer' CHECK (source IN ('timer', 'manual')),
    timer_mode TEXT DEFAULT 'count_up' CHECK (timer_mode IN ('count_up', 'count_down')),
    planned_duration_seconds INTEGER,
    target_end_at TIMESTAMPTZ,
    session_status TEXT NOT NULL DEFAULT 'completed' CHECK (session_status IN ('running', 'completed')),
    last_chime_index INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT chk_session_times CHECK (ended_at IS NULL OR started_at IS NULL OR ended_at >= started_at)
);

-- ==============================================================================
-- Indexes เพื่อประสิทธิภาพการ Query สูงสุด
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_practice_summaries_user_status 
    ON public.practice_summaries (user_id, status, id DESC);

CREATE INDEX IF NOT EXISTS idx_practice_sessions_summary_date 
    ON public.practice_sessions (practice_summary_id, practice_date DESC);

CREATE INDEX IF NOT EXISTS idx_practice_sessions_user_date 
    ON public.practice_sessions (user_id, practice_date DESC);


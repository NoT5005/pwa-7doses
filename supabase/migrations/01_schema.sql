-- ==============================================================================
-- Trigger อัตโนมัติ: สร้าง Profile, เกณฑ์ประเมิน, และขั้นที่ 1 รอบ 1 เมื่อ User สมัครใหม่
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    -- 1. สร้าง Profile
    INSERT INTO public.profiles (user_id, practitioner_name, email)
    VALUES (
        NEW.id,
        COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.raw_user_meta_data->>'name', 'ผู้ปฏิบัติธรรม'),
        NEW.email
    )
    ON CONFLICT (user_id) DO NOTHING;

    -- 2. สร้าง Effort Settings เริ่มต้น
    INSERT INTO public.effort_settings (user_id)
    VALUES (NEW.id)
    ON CONFLICT (user_id) DO NOTHING;

    -- 3. สร้าง Practice Summary ขั้น 1 รอบ 1 เป็นค่าเริ่มต้น
    INSERT INTO public.practice_summaries (user_id, practice_step_id, round_number, status)
    SELECT NEW.id, id, 1, 'active'
    FROM public.practice_steps
    WHERE step_order = 1
    ON CONFLICT (user_id, practice_step_id, round_number) DO NOTHING;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- ติดตั้ง Trigger เข้ากับ auth.users
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
